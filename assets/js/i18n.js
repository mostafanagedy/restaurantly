class RestaurantlyI18n {
  constructor() {
    this.currentLang = localStorage.getItem('restaurantly_lang') || 'en';
    this.init();
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  }

  applyLanguage(lang) {
    this.currentLang = lang;
    localStorage.setItem('restaurantly_lang', lang);

    document.documentElement.setAttribute('lang', lang);
    document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

    const dict = RESTAURANTLY_I18N[lang];
    if (!dict) return;

    // Inner text replacement for elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        if (key === 'heroTitle' || key === 'copyright' || key === 'hoursText' || key === 'credits') {
          el.innerHTML = dict[key];
        } else {
          el.innerText = dict[key];
        }
      }
    });

    // Placeholders for inputs and textareas
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const key = el.getAttribute('data-i18n-ph');
      if (dict[key] !== undefined) {
        el.placeholder = dict[key];
      }
    });

    // Values for input buttons
    document.querySelectorAll('[data-i18n-val]').forEach(el => {
      const key = el.getAttribute('data-i18n-val');
      if (dict[key] !== undefined) {
        el.value = dict[key];
      }
    });

    // Update active state in topbar languages
    document.querySelectorAll('.lang-btn').forEach(btn => {
      const btnLang = btn.getAttribute('data-lang');
      if (btnLang === lang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });

    // Update floating button text
    const floatingLabel = document.getElementById('floatingLangLabel');
    if (floatingLabel) {
      floatingLabel.innerText = lang === 'ar' ? 'English' : 'العربية';
    }
  }

  bindEvents() {
    document.addEventListener('click', (e) => {
      const langBtn = e.target.closest('.lang-btn');
      if (langBtn) {
        e.preventDefault();
        const lang = langBtn.getAttribute('data-lang');
        if (lang) this.applyLanguage(lang);
      }

      const floatBtn = e.target.closest('#floatingLangToggle');
      if (floatBtn) {
        e.preventDefault();
        const nextLang = this.currentLang === 'ar' ? 'en' : 'ar';
        this.applyLanguage(nextLang);
      }
    });
  }
}

document.addEventListener('DOMContentLoaded', () => {
  window.restaurantlyI18n = new RestaurantlyI18n();
});
